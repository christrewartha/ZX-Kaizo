# Builds the Commodore 64 version, Kaiz64o:
#   tools/build_data.ps1   -> build/gen/      (levels, shared with
#                                              the Spectrum version)
#   c64/data/chars.txt     -> build/c64gen/charset_data.c/h
#   c64/data/sprites.txt   -> build/c64gen/sprite_data.c/h
#   c64/data/music.txt     -> build/c64gen/song_data.c (with data/music.txt
#                                              as its intro)
#   SID pitches, sine      -> build/c64gen/tables.c
# then oscar64 compiles build/kaiz64o.prg, and c1541 puts it on a disk
# image, build/kaiz64o.d64. Errors are reported as file:line: so VS Code's
# problem matcher picks them up.
#
#   -Run          start VICE on the result
#   -Start <n>    skip the title and start on level n, for testing

param([switch]$Run, [int]$Start = 0)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$gen = Join-Path $root 'build/c64gen'
New-Item -ItemType Directory -Force $gen | Out-Null

function Fail($file, $line, $msg) {
    [Console]::Error.WriteLine("${file}:${line}:1: error: $msg")
    exit 1
}

function Write-Gen($name, $text) {
    [IO.File]::WriteAllText((Join-Path $gen $name), $text)
}

function Hex-Rows($sb, $bytes, $perRow) {
    for ($i = 0; $i -lt $bytes.Count; $i += $perRow) {
        $n = [Math]::Min($perRow, $bytes.Count - $i)
        $row = for ($j = 0; $j -lt $n; $j++) { '0x{0:X2}' -f $bytes[$i + $j] }
        [void]$sb.AppendLine('    ' + ($row -join ', ') + ',')
    }
}

& powershell -NoProfile -ExecutionPolicy Bypass -File (Join-Path $PSScriptRoot 'build_data.ps1')
if ($LASTEXITCODE) { exit 1 }

# ---------------------------------------------------------------- chars

# Each [name] is followed by 8 rows. 'mc' rows are 4 double-width pixels:
# '.' background, 'a' and 'b' the two shared colours, 'c' the cell's own
# colour. 'hires' rows are 8 pixels, '#' set.
$file = 'c64/data/chars.txt'
$lines = [IO.File]::ReadAllLines((Join-Path $root $file))
$chars = New-Object Collections.Generic.List[object]
$current = $null
for ($i = 0; $i -lt $lines.Count; $i++) {
    $line = ($lines[$i] -replace ';.*$', '').Trim()
    if ($line -eq '') { continue }
    if ($line -match '^\[(\w+)\]\s+(mc|hires)$') {
        if ($current -and $current.Rows.Count -ne 8) { Fail $file $current.Line "[$($current.Name)] has $($current.Rows.Count) rows, needs 8" }
        $current = @{ Name = $Matches[1].ToUpper(); Mode = $Matches[2]; Rows = New-Object Collections.Generic.List[int]; Line = $i + 1 }
        $chars.Add($current)
        continue
    }
    if (-not $current) { Fail $file ($i + 1) 'char row before any [name] mc|hires' }
    if ($current.Rows.Count -eq 8) { Fail $file ($i + 1) "[$($current.Name)] has more than 8 rows" }
    $bits = 0
    if ($current.Mode -eq 'mc') {
        if ($line.Length -ne 4) { Fail $file ($i + 1) "mc row is $($line.Length) pixels wide, needs 4" }
        foreach ($ch in $line.ToCharArray()) {
            $v = '.abc'.IndexOf($ch)
            if ($v -lt 0) { Fail $file ($i + 1) "bad mc pixel '$ch' (use . a b c)" }
            $bits = ($bits -shl 2) -bor $v
        }
    } else {
        if ($line.Length -ne 8) { Fail $file ($i + 1) "hires row is $($line.Length) pixels wide, needs 8" }
        foreach ($ch in $line.ToCharArray()) {
            if ($ch -ne [char]'.' -and $ch -ne [char]'#') { Fail $file ($i + 1) "bad hires pixel '$ch' (use . #)" }
            $bits = ($bits -shl 1) -bor [int]($ch -eq [char]'#')
        }
    }
    $current.Rows.Add($bits)
}
if ($current -and $current.Rows.Count -ne 8) { Fail $file $current.Line "[$($current.Name)] has $($current.Rows.Count) rows, needs 8" }

$charBase = 96                  # below are the ROM font and lower case letters
if ($charBase + $chars.Count -gt 240) { Fail $file 1 "too many chars ($($chars.Count)); codes 240-255 are made at run time" }

$h = New-Object Text.StringBuilder
[void]$h.AppendLine('// Generated by tools/build_c64.ps1 from c64/data/chars.txt - do not edit')
[void]$h.AppendLine('#ifndef CHARSET_DATA_H')
[void]$h.AppendLine('#define CHARSET_DATA_H')
[void]$h.AppendLine()
[void]$h.AppendLine("#define CH_BASE $charBase")
for ($i = 0; $i -lt $chars.Count; $i++) { [void]$h.AppendLine("#define CH_$($chars[$i].Name) $($charBase + $i)") }
[void]$h.AppendLine("#define CH_DATA_COUNT $($chars.Count)")
[void]$h.AppendLine()
[void]$h.AppendLine('extern const unsigned char charset_data[CH_DATA_COUNT * 8];')
[void]$h.AppendLine()
[void]$h.AppendLine('#endif')
Write-Gen 'charset_data.h' $h.ToString()

$c = New-Object Text.StringBuilder
[void]$c.AppendLine('// Generated by tools/build_c64.ps1 from c64/data/chars.txt - do not edit')
[void]$c.AppendLine('#include "charset_data.h"')
[void]$c.AppendLine()
[void]$c.AppendLine('const unsigned char charset_data[CH_DATA_COUNT * 8] = {')
foreach ($ch in $chars) {
    [void]$c.AppendLine("    // CH_$($ch.Name)")
    Hex-Rows $c $ch.Rows 8
}
[void]$c.AppendLine('};')
Write-Gen 'charset_data.c' $c.ToString()

# -------------------------------------------------------------- sprites

# Each [name] is followed by up to 19 rows of up to 10 double-width pixels:
# '.' clear, 'k' and 'w' the shared colours (black and white), 'o' the
# sprite's own colour. Options after the name:
#   mirror   also make a left-facing copy, <NAME>_L
#   outline  also make a hi-res sprite tracing a 1 pixel outline round the
#            art, <NAME>_O (and <NAME>_OL), to lay over it
# The art is placed one double pixel in and one row down from the sprite's
# top-left, so the outline has room on every side.
$file = 'c64/data/sprites.txt'
$lines = [IO.File]::ReadAllLines((Join-Path $root $file))
$arts = New-Object Collections.Generic.List[object]
$current = $null
for ($i = 0; $i -lt $lines.Count; $i++) {
    $line = ($lines[$i] -replace ';.*$', '').Trim()
    if ($line -eq '') { continue }
    if ($line -match '^\[(\w+)\]((\s+(mirror|outline))*)$') {
        $opts = $Matches[2]
        $current = @{ Name = $Matches[1].ToUpper(); Rows = New-Object Collections.Generic.List[string]; Line = $i + 1
                      Mirror = $opts -match 'mirror'; Outline = $opts -match 'outline' }
        $arts.Add($current)
        continue
    }
    if (-not $current) { Fail $file ($i + 1) 'art row before any [name]' }
    if ($line.Length -gt 10) { Fail $file ($i + 1) "row is $($line.Length) pixels wide, max 10" }
    if ($current.Rows.Count -eq 19) { Fail $file ($i + 1) "[$($current.Name)] has more than 19 rows" }
    if ($line -notmatch '^[.kwo]+$') { Fail $file ($i + 1) "bad pixel in '$line' (use . k w o)" }
    $current.Rows.Add($line)
}

$mcValue = @{ [char]'.' = 0; [char]'k' = 1; [char]'o' = 2; [char]'w' = 3 }

# 63 bytes (+1 pad) for a multicolour sprite from art rows
function MC-Block($rows) {
    $b = New-Object byte[] 64
    for ($r = 0; $r -lt $rows.Count; $r++) {
        $row = $rows[$r]
        for ($x = 0; $x -lt $row.Length; $x++) {
            $v = $mcValue[$row[$x]]
            $px = $x + 1; $py = $r + 1
            $byte = $py * 3 + [Math]::Floor($px / 4)
            $shift = 6 - 2 * ($px % 4)
            $b[$byte] = $b[$byte] -bor ($v -shl $shift)
        }
    }
    return ,$b
}

# Hi-res outline: pixels next to (not diagonal) the art but not in it
function Outline-Block($rows) {
    $mask = New-Object 'bool[,]' 21, 24
    for ($r = 0; $r -lt $rows.Count; $r++) {
        $row = $rows[$r]
        for ($x = 0; $x -lt $row.Length; $x++) {
            if ($row[$x] -ne [char]'.') { $mask[($r + 1), (2 * $x + 2)] = $true; $mask[($r + 1), (2 * $x + 3)] = $true }
        }
    }
    $b = New-Object byte[] 64
    for ($y = 0; $y -lt 21; $y++) {
        for ($x = 0; $x -lt 24; $x++) {
            if ($mask[$y, $x]) { continue }
            $near = ($y -gt 0 -and $mask[($y - 1), $x]) -or ($y -lt 20 -and $mask[($y + 1), $x]) -or
                    ($x -gt 0 -and $mask[$y, ($x - 1)]) -or ($x -lt 23 -and $mask[$y, ($x + 1)])
            if ($near) { $b[$y * 3 + [Math]::Floor($x / 8)] = $b[$y * 3 + [Math]::Floor($x / 8)] -bor (0x80 -shr ($x % 8)) }
        }
    }
    return ,$b
}

# Mirror within the art's own 8 pixel box, so left and right copies line up
function Mirror-Rows($rows) {
    $out = New-Object Collections.Generic.List[string]
    foreach ($row in $rows) {
        $padded = $row.PadRight(8, '.')
        $chars = $padded.ToCharArray(); [Array]::Reverse($chars)
        $out.Add((-join $chars))
    }
    return ,$out
}

$blocks = New-Object Collections.Generic.List[object]
$defines = New-Object Collections.Generic.List[string]
function Add-Block($name, $bytes) {
    $defines.Add("#define SP_$name $($blocks.Count)")
    $blocks.Add(@{ Name = $name; Bytes = $bytes })
}
foreach ($a in $arts) {
    if ($a.Rows.Count -eq 0) { Fail $file $a.Line "[$($a.Name)] has no rows" }
    Add-Block $a.Name (MC-Block $a.Rows)
    if ($a.Mirror) { Add-Block "$($a.Name)_L" (MC-Block (Mirror-Rows $a.Rows)) }
    if ($a.Outline) {
        Add-Block "$($a.Name)_O" (Outline-Block $a.Rows)
        if ($a.Mirror) { Add-Block "$($a.Name)_OL" (Outline-Block (Mirror-Rows $a.Rows)) }
    }
}
if ($blocks.Count -gt 120) { Fail $file 1 "too many sprite blocks ($($blocks.Count)), max 120" }

