[void]$h.AppendLine('// Generated by tools/build_c64.ps1 from c64/data/sprites.txt - do not edit')
[void]$h.AppendLine('#ifndef SPRITE_DATA_H')
[void]$h.AppendLine('#define SPRITE_DATA_H')
[void]$h.AppendLine()
foreach ($d in $defines) { [void]$h.AppendLine($d) }
[void]$h.AppendLine("#define SP_COUNT $($blocks.Count)")
[void]$h.AppendLine()
[void]$h.AppendLine('extern const unsigned char sprite_data[SP_COUNT * 64];')
[void]$h.AppendLine()
[void]$h.AppendLine('#endif')
Write-Gen 'sprite_data.h' $h.ToString()

$s = New-Object Text.StringBuilder
[void]$s.AppendLine('// Generated by tools/build_c64.ps1 from c64/data/sprites.txt - do not edit')
[void]$s.AppendLine('#include "sprite_data.h"')
[void]$s.AppendLine()
[void]$s.AppendLine('const unsigned char sprite_data[SP_COUNT * 64] = {')
foreach ($b in $blocks) {
    [void]$s.AppendLine("    // SP_$($b.Name)")
    Hex-Rows $s $b.Bytes 16
}
[void]$s.AppendLine('};')
Write-Gen 'sprite_data.c' $s.ToString()

