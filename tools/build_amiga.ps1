$sampleBytes = New-Object Collections.Generic.List[int]
$offsets = @{}
function Add-Sample($name, $values) {
    $offsets[$name] = $sampleBytes.Count
    foreach ($v in $values) { $sampleBytes.Add([int][Math]::Max(-128, [Math]::Min(127, [Math]::Round($v)))) }
    if ($sampleBytes.Count % 2) { $sampleBytes.Add(0) }
}
Add-Sample 'SILENCE' @(0, 0)
for ($w = 0; $w -lt $waveNames.Count; $w++) {
    foreach ($len in $lengths) {
        $vals = for ($i = 0; $i -lt $len; $i++) {
            $t = $i / $len
            switch ($w) {
                0 { if ($t -lt 0.5) { -100 + 400 * $t } else { 300 - 400 * $t } }
                1 { -100 + 200 * $t }
                default { $duty = [Math]::Max(1, [Math]::Round($len * ($w - 1) / 8)); if ($i -lt $duty) { 90 } else { -90 } }
            }
        }
        Add-Sample "$($waveNames[$w])_$len" $vals
    }
}
$rnd = New-Object Random 64
Add-Sample 'NOISE' (1..2048 | ForEach-Object { $rnd.Next(-100, 101) })

# Drums, at period 212 (about 16.7kHz)
$rate = $paulaClock / 212
$n = [int]($rate * 0.22)
$script:phase = 0.0
Add-Sample 'KICK' (0..($n - 1) | ForEach-Object {
    $t = $_ / $rate
    $f = 45 + 140 * [Math]::Exp(-$t * 30)
    $script:phase += 2 * [Math]::PI * $f / $rate
    120 * [Math]::Sin($script:phase) * [Math]::Exp(-$t * 9)
})
$n = [int]($rate * 0.18)
Add-Sample 'SNARE' (0..($n - 1) | ForEach-Object {
    $t = $_ / $rate
    ($rnd.Next(-100, 101) * [Math]::Exp(-$t * 22)) + 40 * [Math]::Sin(2 * [Math]::PI * 190 * $t) * [Math]::Exp(-$t * 35)
})
$n = [int]($rate * 0.05)
$script:last = 0
Add-Sample 'HAT' (0..($n - 1) | ForEach-Object {
    $t = $_ / $rate
    $v = $rnd.Next(-100, 101); $o = $v - $script:last; $script:last = $v
    $o * 0.5 * [Math]::Exp(-$t * 70)
})

