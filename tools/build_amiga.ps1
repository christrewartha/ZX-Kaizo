function Words($sb, $words, $perRow) {
    for ($i = 0; $i -lt $words.Count; $i += $perRow) {
        $n = [Math]::Min($perRow, $words.Count - $i)
        $row = for ($j = 0; $j -lt $n; $j++) { '0x{0:X4}' -f $words[$i + $j] }
        [void]$sb.AppendLine('    ' + ($row -join ', ') + ',')
    }
}

