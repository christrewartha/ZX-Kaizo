# The longest cycle that keeps the period at 124 or more
function Pitch($hz) {
    for ($l = 0; $l -lt $lengths.Count; $l++) {
        $p = [Math]::Round($paulaClock / ($hz * $lengths[$l]))
        if ($p -ge 124) { return @($l, [Math]::Min(65535, $p)) }
    }
    return @(($lengths.Count - 1), 124)
}
$nl = @(); $np = @()
for ($i = 1; $i -le 84; $i++) {
    $p = Pitch (440 * [Math]::Pow(2, (($i + 23) - 69) / 12))
    $nl += $p[0]; $np += $p[1]
}
[void]$snd.AppendLine('const unsigned char note_length[84] = { ' + ($nl -join ', ') + ' };')
[void]$snd.AppendLine('const unsigned short note_period[84] = { ' + ($np -join ', ') + ' };')
$sl = @(); $sp = @()
for ($i = 0; $i -lt 256; $i++) {
    $p = Pitch ([Math]::Max(1, $i) * 256 * 985248 / 16777216)
    $sl += $p[0]; $sp += $p[1]
}
[void]$snd.AppendLine('const unsigned char sfx_length[256] = { ' + ($sl -join ', ') + ' };')
[void]$snd.AppendLine('const unsigned short sfx_period[256] = { ' + ($sp -join ', ') + ' };')
